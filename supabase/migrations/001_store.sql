create extension if not exists pgcrypto;

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  name_sq text not null,
  name_en text not null,
  category text not null default 'sneakers',
  image_key text not null default 'shooe_tilt_1.png',
  description_sq text not null default '',
  description_en text not null default '',
  price numeric(12,2) not null check (price >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique not null,
  role text not null default 'customer' check (role in ('customer','admin')),
  created_at timestamptz not null default now()
);

alter table public.products enable row level security;
alter table public.profiles enable row level security;

create policy "products_public_read" on public.products for select using (active = true or exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));
create policy "products_admin_insert" on public.products for insert with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));
create policy "products_admin_update" on public.products for update using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin')) with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));
create policy "products_admin_delete" on public.products for delete using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));
create policy "profile_self_read" on public.profiles for select using (id = auth.uid());

